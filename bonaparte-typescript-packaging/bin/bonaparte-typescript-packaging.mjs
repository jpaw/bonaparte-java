#!/usr/bin/env node

import { existsSync } from 'node:fs';
import { cp, copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { XMLParser } from 'fast-xml-parser';

const command = process.argv[2];
const sourceRoot = path.resolve(process.env.TS_PACKAGE_SOURCE_ROOT ?? process.cwd());
const targetDirectory = path.resolve(process.env.MAVEN_TARGET_DIRECTORY ?? path.join(sourceRoot, 'target'));
const workspace = path.join(targetDirectory, 'npm-src');
const configPath = path.resolve(
  process.env.TS_PACKAGING_CONFIG ?? path.join(process.cwd(), 'bonaparte-typescript-packaging.json'),
);
const config = JSON.parse(await readFile(configPath, 'utf8'));
const moduleRoot = path.resolve(process.env.TS_API_MODULE_ROOT ?? sourceRoot);
const reactorRoot = path.resolve(process.env.TS_REACTOR_ROOT ?? path.resolve(moduleRoot, '..'));
const packagingPom = path.resolve(process.env.TS_PACKAGING_POM ?? path.join(moduleRoot, 'pom.xml'));
const generatedSourceDirectory = config.generatedSourceDirectory ?? 'src/generated/ts';
const npmCli = process.env.npm_execpath;

function requiredEnvironment(...names) {
  const values = names.map(name => process.env[name]);
  if (values.some(value => !value)) {
    throw new Error(`Missing required environment variable: ${names.filter((_, index) => !values[index]).join(', ')}`);
  }
  return values;
}

function runNode(args, options = {}) {
  const result = spawnSync(process.execPath, args, { encoding: 'utf8', ...options });
  if (result.status !== 0) {
    throw new Error(`Command failed with exit code ${result.status}: ${result.stderr || result.stdout || args.join(' ')}`);
  }
  return result;
}

function runNpm(args, options = {}) {
  if (!npmCli) throw new Error('Run the packaging commands through npm so npm_execpath is available.');
  return runNode([npmCli, ...args], options);
}

function registryArguments(registryUrl) {
  if (!registryUrl) return [];
  const registry = new URL(registryUrl);
  return ['--registry=https://registry.npmjs.org', `--@arvato-systems-jacs:registry=${registry.href}`];
}

function mavenToNpmVersion(projectVersion, buildTimestamp) {
  const match = /^(\d+)\.(\d+)(?:\.(\d+))?(-SNAPSHOT)?$/.exec(projectVersion ?? '');
  if (!match) throw new Error(`Unsupported Maven project version: ${projectVersion ?? '(missing)'}`);
  const [, major, minor, patch = '0', snapshot] = match;
  if (!snapshot) return `${major}.${minor}.${patch}`;
  const timestamp = new Date(buildTimestamp ?? '');
  if (Number.isNaN(timestamp.getTime())) throw new Error(`Invalid Maven build timestamp: ${buildTimestamp ?? '(missing)'}`);
  const suffix = [
    timestamp.getUTCFullYear(),
    String(timestamp.getUTCMonth() + 1).padStart(2, '0'),
    String(timestamp.getUTCDate()).padStart(2, '0'),
    String(timestamp.getUTCHours()).padStart(2, '0'),
    String(timestamp.getUTCMinutes()).padStart(2, '0'),
    String(timestamp.getUTCSeconds()).padStart(2, '0'),
  ].join('');
  return `${major}.${minor}.${patch}-snapshot.${suffix}`;
}

function validateEntryPointName(entryPoint) {
  if (typeof entryPoint !== 'string' || !/^[A-Za-z0-9._-]+$/.test(entryPoint) || entryPoint === '.' || entryPoint === '..') {
    throw new Error(`Invalid generated entry point: ${entryPoint}`);
  }
}

async function loadEntryPoints() {
  const parser = new XMLParser({ removeNSPrefix: true, isArray: name => name === 'dependency' });
  const pom = parser.parse(await readFile(packagingPom, 'utf8'));
  const dependencies = pom.project.dependencies?.dependency ?? [];
  const entryPoints = dependencies.map(dependency => dependency.artifactId);
  if (entryPoints.length === 0 || new Set(entryPoints).size !== entryPoints.length) {
    throw new Error('The packaging POM must declare a nonempty, unique set of API dependencies.');
  }
  entryPoints.forEach(validateEntryPointName);
  return entryPoints;
}

async function removeGeneratedEntryPoint(packageRoot, entryPoint) {
  const destination = path.join(packageRoot, entryPoint);
  if (!existsSync(destination)) return;
  const indexPath = path.join(destination, 'index.ts');
  const packageConfig = path.join(destination, 'ng-package.json');
  if (!existsSync(packageConfig) || !existsSync(indexPath)
    || !(await readFile(indexPath, 'utf8')).startsWith('// autogenerated by bonaparte DSL.')) {
    throw new Error(`Refusing to overwrite non-generated package directory: ${destination}`);
  }
  await rm(destination, { recursive: true, force: true });
}

async function assembleGeneratedSources() {
  const entryPoints = await loadEntryPoints();
  const manifestPath = path.join(targetDirectory, 'generated-ts-entrypoints.json');
  if (existsSync(manifestPath)) {
    const previous = JSON.parse(await readFile(manifestPath, 'utf8'));
    for (const entryPoint of previous) {
      validateEntryPointName(entryPoint);
      await removeGeneratedEntryPoint(process.cwd(), entryPoint);
    }
  }
  for (const entryPoint of entryPoints) {
    const source = path.join(reactorRoot, entryPoint, generatedSourceDirectory, entryPoint);
    if (!existsSync(path.join(source, 'ng-package.json')) || !existsSync(path.join(source, 'index.ts'))) {
      throw new Error(`Missing generated entry point: ${source}. Build the API reactor with -Dts-api=true first.`);
    }
    await removeGeneratedEntryPoint(process.cwd(), entryPoint);
    await cp(source, path.join(process.cwd(), entryPoint), { recursive: true });
  }
  await mkdir(targetDirectory, { recursive: true });
  await writeFile(manifestPath, `${JSON.stringify(entryPoints, null, 2)}\n`);
  console.log(`Assembled ${entryPoints.length} generated TypeScript entry points.`);
}

async function prepareWorkspace() {
  const inputs = [
    'index.ts',
    'ng-package.json',
    'package.json',
    'tsconfig.json',
    'tsconfig.lib.prod.json',
    'bonaparte-typescript-packaging.json',
  ];
  await rm(workspace, { recursive: true, force: true });
  await mkdir(workspace, { recursive: true });
  for (const input of inputs) {
    const source = path.join(sourceRoot, input);
    if (!existsSync(source)) throw new Error(`Missing npm package input: ${source}`);
    await cp(source, path.join(workspace, input), { recursive: true });
  }
  const manifestPath = path.join(workspace, 'package.json');
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  for (const [packageName, environmentName] of Object.entries(config.managedDependencyVersions ?? {})) {
    const mavenVersion = process.env[environmentName];
    const match = /^(\d+)\.(\d+)(?:\.(\d+))?(-SNAPSHOT)?$/.exec(mavenVersion ?? '');
    if (!match) throw new Error(`Unsupported Maven version for ${packageName}: ${mavenVersion ?? '(missing)'}`);
    const [, major, minor, patch = '0', snapshot] = match;
    if (!(packageName in (manifest.dependencies ?? {}))) throw new Error(`Missing ${packageName} dependency`);
    manifest.dependencies[packageName] = snapshot
      ? `>=${major}.${minor}.${patch}-snapshot.0 <${major}.${minor}.${patch}`
      : `${major}.${minor}.${patch}`;
  }
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  const registryUrl = process.env.NPM_REGISTRY_URL ?? 'https://npm.pkg.github.com';
  const managedPackages = Object.keys({
    ...(manifest.dependencies ?? {}),
    ...(manifest.peerDependencies ?? {}),
  }).filter(name => name.startsWith('@arvato-systems-jacs/'));
  const packageVersions = [];
  for (const packageName of managedPackages) {
    const range = manifest.dependencies?.[packageName] ?? manifest.peerDependencies?.[packageName];
    const result = runNpm(['view', `${packageName}@${range}`, 'version', '--json', ...registryArguments(registryUrl)], {
      cwd: workspace,
    });
    const versions = JSON.parse(result.stdout);
    const version = (Array.isArray(versions) ? versions : [versions]).at(-1);
    if (!version) throw new Error(`No published version of ${packageName} satisfies ${range}`);
    packageVersions.push(`${packageName}@${version}`);
  }
  runNpm(['install', '--no-save', '--package-lock=false', '--ignore-scripts', '--no-audit', '--no-fund', ...packageVersions, ...registryArguments(registryUrl)], {
    cwd: workspace,
    stdio: 'inherit',
  });
  await rm(path.join(workspace, 'package-lock.json'), { force: true });
  console.log(`Prepared npm workspace at ${workspace}.`);
}

async function packageArtifact() {
  const [projectVersion, buildTimestamp] = requiredEnvironment('MAVEN_PROJECT_VERSION', 'MAVEN_BUILD_TIMESTAMP');
  const distribution = path.join(targetDirectory, 'npm-dist');
  await rm(distribution, { recursive: true, force: true });
  await cp(path.join(process.cwd(), 'dist'), distribution, { recursive: true });
  const manifestPath = path.join(distribution, 'package.json');
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  manifest.version = mavenToNpmVersion(projectVersion, buildTimestamp);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  const packed = runNpm(['pack', '--json', '--pack-destination', targetDirectory], { cwd: distribution });
  const packages = JSON.parse(packed.stdout);
  if (!Array.isArray(packages) || packages.length !== 1 || typeof packages[0]?.filename !== 'string') {
    throw new Error('npm pack must return exactly one package with a filename.');
  }
  const artifactName = config.artifactName;
  validateEntryPointName(artifactName);
  await copyFile(path.join(targetDirectory, packages[0].filename), path.join(targetDirectory, `${artifactName}-npm.tgz`));
  console.log(`Packed ${manifest.name}@${manifest.version}.`);
}

async function publishPackage() {
  const [target] = requiredEnvironment('MAVEN_TARGET_DIRECTORY');
  const registryUrl = process.env.NPM_REGISTRY_URL ?? 'https://npm.pkg.github.com';
  const token = process.env.NODE_AUTH_TOKEN;
  const registry = new URL(registryUrl);
  const localRegistry = registry.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(registry.hostname);
  if ((!token && !localRegistry) || !npmCli) {
    throw new Error('NODE_AUTH_TOKEN is required except for a loopback registry.');
  }
  const distribution = path.join(path.resolve(target), 'npm-dist');
  const manifest = JSON.parse(await readFile(path.join(distribution, 'package.json'), 'utf8'));
  const npmrc = path.join(distribution, '.npmrc');
  await writeFile(npmrc, `@arvato-systems-jacs:registry=${registryUrl}\n//${registry.host}/:_authToken=${token ?? 'local-development-only'}\n`, { mode: 0o600 });
  try {
    const tag = manifest.version.includes('-snapshot.') ? 'snapshot' : 'latest';
    const args = ['publish', '--registry', registryUrl, '--tag', tag];
    if (!localRegistry) args.push('--access', 'restricted');
    runNpm(args, { cwd: distribution, stdio: 'inherit' });
  } finally {
    await rm(npmrc, { force: true });
  }
}

async function testConsumer() {
  const consumerFixture = process.env.TS_CONSUMER_FILE ?? config.consumerFile;
  if (!consumerFixture) throw new Error('TS_CONSUMER_FILE or consumerFile is required for test-consumer.');
  const consumer = await mkdtemp(path.join(targetDirectory, 'npm-consumer-'));
  const registryUrl = process.env.NPM_REGISTRY_URL ?? 'https://npm.pkg.github.com';
  const registryToken = process.env.NODE_AUTH_TOKEN;
  try {
    const packageManifest = JSON.parse(await readFile(path.join(targetDirectory, 'npm-dist/package.json'), 'utf8'));
    await writeFile(path.join(consumer, 'package.json'), `${JSON.stringify({
      private: true,
      type: 'module',
      dependencies: {
        ...packageManifest.peerDependencies,
        '@angular/compiler': packageManifest.peerDependencies?.['@angular/core'],
      },
    }, null, 2)}\n`);
    const registry = new URL(registryUrl);
    const lines = [`@arvato-systems-jacs:registry=${registryUrl}`];
    if (registryToken) lines.push(`//${registry.host}/:_authToken=${registryToken}`);
    await writeFile(path.join(consumer, '.npmrc'), `${lines.join('\n')}\n`, { mode: 0o600 });
    runNpm(['install', path.join(targetDirectory, `${config.artifactName}-npm.tgz`), '--ignore-scripts', '--no-audit', '--no-fund', ...registryArguments(registryUrl)], {
      cwd: consumer,
      stdio: 'inherit',
    });
    const installedManifest = JSON.parse(await readFile(path.join(consumer, 'node_modules', ...packageManifest.name.split('/'), 'package.json'), 'utf8'));
    if (installedManifest.name !== packageManifest.name) throw new Error(`Installed package name mismatch: ${installedManifest.name}`);
    const fixture = path.resolve(consumerFixture);
    await copyFile(fixture, path.join(consumer, 'consumer.mts'));
    const require = createRequire(pathToFileURL(path.join(workspace, 'package.json')).href);
    const tsc = require.resolve('typescript/bin/tsc');
    runNode([tsc, '--strict', '--skipLibCheck', 'false', '--target', 'ES2022', '--module', 'NodeNext', '--moduleResolution', 'NodeNext', '--outDir', path.join(consumer, 'compiled'), path.join(consumer, 'consumer.mts')], {
      cwd: consumer,
      stdio: 'inherit',
    });
    runNode([path.join(consumer, 'compiled/consumer.mjs')], { cwd: consumer, stdio: 'inherit' });
  } finally {
    await rm(consumer, { recursive: true, force: true });
  }
}

switch (command) {
  case 'prepare-workspace':
    await prepareWorkspace();
    break;
  case 'assemble-generated':
    await assembleGeneratedSources();
    break;
  case 'package':
    await packageArtifact();
    break;
  case 'publish':
    await publishPackage();
    break;
  case 'test-consumer':
    await testConsumer();
    break;
  default:
    throw new Error(`Unknown command: ${command ?? '(missing)'}. Expected prepare-workspace, assemble-generated, package, publish, or test-consumer.`);
}
